    fun normalizeLocale(value: String?): String {
        return if (value == "ru") "ru" else "en"
    }

    fun t(
        locale: String?,
        key: String,
        params: Map<String, String> = emptyMap(),
    ): String {
        val normalized = normalizeLocale(locale)
        var text =
            translations[normalized]?.get(key)
                ?: translations["en"]?.get(key)
                ?: key
        params.forEach { (paramKey, value) ->
            text = text.replace("{$paramKey}", value)
        }
        return text
    }
